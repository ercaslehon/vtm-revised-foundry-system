import fs from "node:fs";
import { deriveVampireRollEffect } from "./data/vampire/vampire-roll-effects.mjs";

const path = new URL("../data/vtm-revised-merits-flaws.generated.json", import.meta.url);
const data = JSON.parse(fs.readFileSync(path, "utf8"));
const records = [...(data.merits ?? []), ...(data.flaws ?? [])];

for (const entry of records) {
  const sourceEntry = { ...entry, effect: { ...(entry.effect ?? {}) } };
  delete sourceEntry.effect.appliesToRoll;
  delete sourceEntry.effect.automatic;
  delete sourceEntry.effect.conditional;
  delete sourceEntry.effect.matchAll;
  delete sourceEntry.effect.selectors;
  const derived = deriveVampireRollEffect(sourceEntry);
  entry.effect = {
    ...(entry.effect ?? {}),
    difficultyModifier: derived.difficulty,
    diceModifier: derived.dice,
    appliesToRoll: derived.applicable,
    automatic: false,
    conditional: true,
    matchAll: derived.matchAll,
    selectors: derived.selectors,
    notes: derived.applicable ? `<p>${entry.summary || "Условия применения указаны в тексте карточки."}</p>` : "<p>Не изменяет обычный запас кубиков или сложность броска.</p>"
  };
}

fs.writeFileSync(path, `${JSON.stringify(data, null, 2)}\n`);
const generatedPath = new URL("./data/vampire/vampire-roll-effects.generated.mjs", import.meta.url);
const byName = Object.fromEntries(records.map(entry => [String(entry.name).toLocaleLowerCase("ru-RU").replaceAll("ё", "е"), {
  applicable: Boolean(entry.effect.appliesToRoll), selectors: entry.effect.selectors, matchAll: Boolean(entry.effect.matchAll),
  dice: Number(entry.effect.diceModifier || 0), difficulty: Number(entry.effect.difficultyModifier || 0), note: String(entry.effect.notes || "").replace(/<[^>]*>/g, " ").replace(/\s+/g, " ").trim()
}]));
fs.writeFileSync(generatedPath, `// Generated by scripts/enrich-vampire-roll-effects.mjs.\nexport const VAMPIRE_ROLL_EFFECTS_BY_NAME = ${JSON.stringify(byName, null, 2)};\n`);
const applicable = records.filter(entry => entry.effect.appliesToRoll);
const numeric = applicable.filter(entry => entry.effect.diceModifier || entry.effect.difficultyModifier);
console.log(`Enriched ${records.length} records: ${applicable.length} roll-related, ${numeric.length} with fixed numeric modifiers.`);
